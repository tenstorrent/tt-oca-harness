#!/usr/bin/env python3
"""
Apply optional per-word endianness swaps and bank reordering to a 64-bit-per-line
ROM image (``.bin64``) generated by the firmware build.

The input format is one 64-bit binary string per line, MSB on the left, with an
optional Verilog-style ``@<addr>`` directive to reposition the write pointer.
When ``--rom-endianness-swap`` is requested each word's byte order is reversed.
When ``--rom-bank-swap`` is specified, 16 KiB banks are repositioned to match
the RTL bank wiring.
"""

from __future__ import annotations

import argparse
import pathlib
import sys
from collections.abc import Sequence

# Fixed geometry: four 32 KiB banks, 64-bit words.
BANK_SIZE_BYTES = 32 * 1024
WORD_SIZE_BYTES = 8
WORDS_PER_BANK = BANK_SIZE_BYTES // WORD_SIZE_BYTES

DEFAULT_BANK_ORDER: tuple[int, int, int, int] = (0, 1, 2, 3)

BANK_SWAP_ORDERS: dict[int, tuple[int, int, int, int]] = {
    0: (0, 1, 2, 3),
    1: (0, 1, 3, 2),
    2: (0, 2, 1, 3),
    3: (0, 2, 3, 1),
    4: (0, 3, 1, 2),
    5: (0, 3, 2, 1),
    6: (1, 0, 2, 3),
    7: (1, 0, 3, 2),
    8: (1, 2, 0, 3),
    9: (1, 2, 3, 0),
    10: (1, 3, 0, 2),
    11: (1, 3, 2, 0),
    12: (2, 0, 1, 3),
    13: (2, 0, 3, 1),
    14: (2, 1, 0, 3),
    15: (2, 1, 3, 0),
    16: (2, 3, 0, 1),
    17: (2, 3, 1, 0),
    18: (3, 0, 1, 2),
    19: (3, 0, 2, 1),
    20: (3, 1, 0, 2),
    21: (3, 1, 2, 0),
    22: (3, 2, 0, 1),
    23: (3, 2, 1, 0),
    24: (0, 1, 2, 3),
    25: (0, 1, 2, 3),
    26: (0, 1, 2, 3),
    27: (0, 1, 2, 3),
    28: (0, 1, 2, 3),
    29: (0, 1, 2, 3),
    30: (0, 1, 2, 3),
    31: (0, 1, 2, 3),
}


def load_rom_words(path: pathlib.Path) -> tuple[list[tuple[int, str]], bool]:
    """Read the input file and return (address, word) pairs plus directive flag."""
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {path}")

    entries: list[tuple[int, str]] = []
    current_addr = 0
    saw_address_directive = False

    for lineno, raw_line in enumerate(path.read_text().splitlines(), start=1):
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("@"):
            try:
                current_addr = int(line[1:], 0)
            except ValueError as exc:
                raise ValueError(f"Invalid address directive on line {lineno}: {line}") from exc
            if current_addr < 0:
                raise ValueError(f"Negative address on line {lineno}: {line}")
            saw_address_directive = True
            continue
        if len(line) != 64 or any(c not in "01" for c in line):
            raise ValueError(f"Expected 64 binary digits per line (line {lineno!r}: {line}).")
        entries.append((current_addr, line))
        current_addr += 1

    return entries, saw_address_directive


def _swap_word_endianness(word: str) -> str:
    """Reverse the order of bytes within the 64-bit word."""
    bytestride = 8
    chunks = [word[i : i + bytestride] for i in range(0, len(word), bytestride)]
    if len(chunks) != 8:
        raise ValueError("Word length must be exactly 64 bits.")
    return "".join(reversed(chunks))


def apply_endianness_swap(entries: Sequence[tuple[int, str]]) -> list[tuple[int, str]]:
    """Apply a byte-level endianness swap to every word."""
    return [(addr, _swap_word_endianness(word)) for addr, word in entries]


def reorder_banks(
    entries: Sequence[tuple[int, str]], order: Sequence[int]
) -> list[tuple[int, str]]:
    if len(order) != 4:
        raise ValueError("Exactly four banks are expected in the swap order.")
    if not entries:
        return []

    if set(order) != {0, 1, 2, 3}:
        raise ValueError(f"Incomplete bank mapping provided: {order}")

    remapped: list[tuple[int, str]] = []
    for addr, word in entries:
        bank_idx = addr // WORDS_PER_BANK
        offset = addr % WORDS_PER_BANK
        if bank_idx >= len(order):
            raise ValueError(
                f"Encountered word at bank {bank_idx}, which is outside the supported range."
            )
        new_bank_idx = order[bank_idx]
        new_addr = new_bank_idx * WORDS_PER_BANK + offset
        remapped.append((new_addr, word))

    return remapped


def _addresses_are_sequential(entries: Sequence[tuple[int, str]]) -> bool:
    if not entries:
        return True
    sorted_entries = sorted(entries, key=lambda item: item[0])
    start_addr = sorted_entries[0][0]
    if start_addr != 0:
        return False
    for idx, (addr, _) in enumerate(sorted_entries):
        if addr != idx:
            return False
    return True


def format_rom_words(
    entries: Sequence[tuple[int, str]], force_addresses: bool = False
) -> list[str]:
    if not entries:
        return []

    sorted_entries = sorted(entries, key=lambda item: item[0])

    if not force_addresses and _addresses_are_sequential(sorted_entries):
        return [word for _, word in sorted_entries]

    lines: list[str] = []
    next_addr = None
    for addr, word in sorted_entries:
        if next_addr is None or addr != next_addr:
            lines.append(f"@{addr:X}")
            next_addr = addr
        lines.append(word)
        next_addr = next_addr + 1
    return lines


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Modify a .bin64 ROM image with optional endianness and bank swaps."
    )
    parser.add_argument("input_file", help="Path to the source .bin64 file.")
    parser.add_argument(
        "--output-file",
        "-o",
        help="Path to write the modified .bin64 (default: stdout).",
    )
    parser.add_argument(
        "--rom-endianness-swap",
        action="store_true",
        help="Reverse byte order within each 64-bit word.",
    )
    parser.add_argument(
        "--rom-bank-swap",
        type=lambda value: int(value, 0),
        default=0,
        help="5-bit bank swap code (0-31) matching RTL mapping.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    input_path = pathlib.Path(args.input_file)

    try:
        entries, saw_address_directive = load_rom_words(input_path)
    except (FileNotFoundError, ValueError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2

    if args.rom_endianness_swap:
        entries = apply_endianness_swap(entries)

    swap_code = args.rom_bank_swap
    if not 0 <= swap_code <= 31:
        print(
            f"Error: rom_bank_swap must be within 0..31 (received {swap_code}).",
            file=sys.stderr,
        )
        return 2

    order = BANK_SWAP_ORDERS.get(swap_code, DEFAULT_BANK_ORDER)
    force_addresses = saw_address_directive
    if order != DEFAULT_BANK_ORDER or swap_code != 0:
        entries = reorder_banks(entries, order)
        force_addresses = True

    lines = format_rom_words(entries, force_addresses=force_addresses)
    output_text = "\n".join(lines) + ("\n" if lines else "")

    if args.output_file:
        out_path = pathlib.Path(args.output_file)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(output_text)
    else:
        sys.stdout.write(output_text)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
