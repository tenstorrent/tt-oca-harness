"""smu_xbar_self_route_sep_test - a sep_out request into the SEP aperture answers DECERR.

The crossbar routing table of hw/sys/smu/doc/index.adoc ("AXI Crossbar")
gives the sep_out row's SEP-aperture cell DECERR, generated by the crossbar
itself. The SEP debug module's system bus, the SEP master the bench drives,
writes and reads a word of an admitted page with SEP_GLOBAL_BASE_ADDR moved
onto that page: both report an error on sbcs.sberror, the crossbar accepts both on sep_out,
and the sep_in, smc_in and ext_out taps do not move. The same word with the base at
its reset value, an egress round trip, is the control.

CCACHE_DISABLE=1 python3 tools/dv/run_dv.py --dut smu \\
    --items smu_xbar_self_route_sep_test --tool verilator
"""

from __future__ import annotations

import pyuvm
from seq_lib.smu_xbar_self_route_sep_test_seq import smu_xbar_self_route_sep_test_seq
from smu_base_test import smu_base_test


@pyuvm.test()
class smu_xbar_self_route_sep_test(smu_base_test):
    """DECERR for sep_out into the SEP aperture, with the egress control."""

    use_shared_env = True

    async def run_scenario(self) -> None:
        self.logger.info("DUT_TAG=WRAPPER smu_xbar_self_route_sep_test SEP=1 DTP TAP -> SEP DM SBA")
        seq = smu_xbar_self_route_sep_test_seq(self)
        await seq.run()
        assert seq.done, "crossbar SEP self-route scenario incomplete"
