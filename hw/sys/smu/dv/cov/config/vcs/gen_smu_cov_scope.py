"""Write smu_wrapper_cov_scope.hier, the VCS coverage scope of the smu DUT.

The scope follows the rule the SEP and SMC scopes state: the bench and the
library and interconnect cells leave the database, and a subsystem graded on a
bench of its own leaves as an instance tree. What remains is the SMU's own
logic: `smu_wrapper`, `smu`, `smu_axi_xbar`, `axi_window_remap` and every
other unit instantiated under `u_smu` outside the SMC, DTP and SEP trees.

The `cov/sv` functional-coverage modules leave the code and toggle metrics
only. Their `cover property` statements stay in the assertion metric and their
covergroups are outside `-cm_hier` altogether, so the functional figures still
read them.

    python3 hw/sys/smu/dv/cov/config/vcs/gen_smu_cov_scope.py [--check]

Reads the filelists a `run_dv.py --dut smu` build leaves under
hw/sys/smu/dv/build, so run a build (any tool) first; `--check` exits 1 when
the committed file is out of date instead of rewriting it.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[6]
FILELISTS = (
    ROOT / "hw/sys/smu/dv/build/smu_wrapper_dut_compile.f",
    ROOT / "hw/sys/smu/dv/build/smu_wrapper_bender.f",
)
OUT = HERE / "smu_wrapper_cov_scope.hier"
TOP = "smu_wrapper_uvm_top"

# (reason, source-path matcher). A unit compiled from a matching path leaves
# every metric under that reason. The library and interconnect classes are the
# ones hw/sys/smc/dv/cov/config/vcs/gen_smc_cov_scope.py names, so a cell that
# leaves the SMC figure leaves this one too.
DROPPED: tuple[tuple[str, re.Pattern[str]], ...] = (
    (
        "bench",
        re.compile(r"/hw/sys/(smu|smc)/dv/(tb|models)/|/hw/common/dv/vip/|/hw/ip/[^/]+/dv/"),
    ),
    ("library cells", re.compile(r"/vendor/pulp-platform/common_cells/")),
    ("library cells", re.compile(r"/vendor/lowRISC/opentitan/.*/prim[^/]*/")),
    ("library cells", re.compile(r"/hw/common/och_prim/")),
    (
        "interconnect cells",
        re.compile(r"/vendor/pulp-platform/(axi|apb|register_interface|axi_stream|obi)/"),
    ),
)
# Units dropped by name: a package carries no logic and would otherwise report
# an assertion row of its own.
DROPPED_UNITS: tuple[tuple[str, str], ...] = (("package", "axi_pkg"),)
# Units compiled from these paths leave the code and toggle metrics but stay in
# the assertion metric, which carries their cover properties.
FCOV = re.compile(r"/hw/sys/smu/dv/cov/sv/")
FCOV_METRICS = "line+cond+fsm+branch+tgl"
# Instance trees dropped whole, each with the reason it is graded elsewhere.
DROPPED_TREES: tuple[tuple[str, tuple[str, ...]], ...] = (
    (
        "subsystems graded on their own benches (hw/sys/smc/dv, hw/sys/dtp/dv, hw/sys/sep/dv)",
        (
            f"{TOP}.u_dut.u_smu.u_smc",
            f"{TOP}.u_dut.u_smu.u_dtp",
            f"{TOP}.u_dut.u_smu.gen_sep.u_sep",
        ),
    ),
    (
        "integration shells: the SMC and SEP adopter-side collateral, owned by those packages",
        (
            f"{TOP}.u_dut.u_smc_ip_integration",
            f"{TOP}.u_dut.u_sep_ip_integration",
        ),
    ),
    (
        "bench AXI egress: the struct bridge, register cut and interface of the outbound port",
        (
            f"{TOP}.u_axi_out_bridge",
            f"{TOP}.u_axi_out_cut",
            f"{TOP}.u_axi_out_if",
        ),
    ),
)
UNIT = re.compile(
    r"^\s*(?:module|macromodule|interface|program)\s+(?:automatic\s+)?"
    r"([A-Za-z_][A-Za-z0-9_$]*)",
    re.M,
)
COMMENTS = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)

HEADER = f"""\
// SPDX-License-Identifier: Apache-2.0
// SPDX-FileCopyrightText: 2026 Tenstorrent USA, Inc.
//
// VCS coverage scope for the smu DUT (`--dut smu`). Generated by
// gen_smu_cov_scope.py from the build filelists on the rule the SEP and SMC
// scopes state: the bench, the library and interconnect cells and the
// subsystems graded on benches of their own leave the database; the SMU's own
// logic stays graded. README.md says what stays and why.
//
// Regenerate after a build whenever the compiled source set changes.

// testbench top's own body; its children are named below or stay
-tree {TOP} 1
"""


def compiled_sources() -> list[Path]:
    out: list[Path] = []
    for fl in FILELISTS:
        if not fl.is_file():
            raise SystemExit(f"{fl} not found: run a --dut smu build first")
        for line in fl.read_text().splitlines():
            line = line.strip()
            if line.endswith((".sv", ".v")) and not line.startswith(("+", "-")):
                out.append(Path(line))
    return out


def units_in(src: Path) -> set[str]:
    try:
        text = COMMENTS.sub("", src.read_text(errors="replace"))
    except OSError:
        return set()
    return {m.group(1) for m in UNIT.finditer(text)}


def classify(sources: list[Path]) -> tuple[dict[str, list[str]], list[str]]:
    """Map each drop reason to its sorted units, and list the fcov units."""
    units: dict[str, set[str]] = {reason: set() for reason, _ in DROPPED}
    fcov: set[str] = set()
    for src in sources:
        if FCOV.search(str(src)):
            fcov |= units_in(src)
            continue
        reason = next((r for r, pattern in DROPPED if pattern.search(str(src))), None)
        if reason is not None:
            units[reason] |= units_in(src)
    for reason, unit in DROPPED_UNITS:
        units.setdefault(reason, set()).add(unit)
    return {r: sorted(n) for r, n in units.items() if n}, sorted(fcov)


def render(units: dict[str, list[str]], fcov: list[str]) -> str:
    out = [HEADER]
    for reason, trees in DROPPED_TREES:
        out.append(f"\n// {reason}\n")
        out.extend(f"-tree {t}\n" for t in trees)
    for reason in sorted(units):
        out.append(f"\n// {reason}\n")
        out.extend(f"-module {u}\n" for u in units[reason])
    out.append(
        "\n// functional-coverage monitors (cov/sv): out of the code and toggle metrics,"
        "\n// kept in the assertion metric for their cover properties\n"
        f"begin {FCOV_METRICS}\n"
    )
    out.extend(f"  -module {u}\n" for u in fcov)
    out.append("end\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", maxsplit=1)[0])
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args(argv)
    text = render(*classify(compiled_sources()))
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is out of date; rerun without --check", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"{OUT}: {text.count('-module ')} units excluded")
    return 0


if __name__ == "__main__":
    sys.exit(main())
