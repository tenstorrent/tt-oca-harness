// Attaches the shared AXI checker to every smu_axi_xbar instance under the formal top, one
// instance per crossbar port. On the three initiator ports (sep_out, smc_out, ext_in) the
// environment drives the request and the crossbar is the subordinate: the instance assumes the
// master rules and asserts the crossbar's. On the three target ports (sep_in, smc_in, ext_out) the
// crossbar is the master: the instance asserts its rules and assumes the subordinate's. Every port
// is AXI4 with a 56-bit address and 64-bit data; the initiator ports carry 8-bit IDs and the
// target ports the 10-bit IDs of smu_axi_xbar_pkg, wide enough to route each response back.
// MAX_OUTSTANDING bounds every port at eight requests per direction.

bind smu_axi_xbar ocah_axi_fv #(
  .IS_LITE             (1'b0),
  .ADDR_WIDTH          (smu_axi_xbar_pkg::XbarAddrWidth),
