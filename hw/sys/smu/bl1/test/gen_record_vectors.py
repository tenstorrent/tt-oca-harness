"""Emit a C header of reference vectors for the SMC BL1 measurement record.

The record is 76 bytes, little-endian: type[16], load_addr u64, entry_point u64, length u32,
kind u32, digest[32], error u32. The soft PCR extends as SHA256(pcr || SHA256(record)) from
32 zero bytes, as the SEP ROM's measurement slots do.
"""

import hashlib
import struct

RECORDS = {
    "staged": dict(
        type=b"OCAHSMC BLSTAGE1",
        load_addr=0xC0080000,
        entry_point=0x40,
        length=1024,
        kind=1,
        digest=bytes(range(32)),
        error=0,
    ),
    "failure": dict(
        type=b"OCAHSMC BLSTAGE1",
        load_addr=0xC0080000,
        entry_point=0x40,
        length=1024,
        kind=2,
        digest=bytes(32),
        error=0x0192,
    ),
}


def serialize(r):
    return struct.pack(
        "<16sQQII32sI",
        r["type"],
        r["load_addr"],
        r["entry_point"],
        r["length"],
        r["kind"],
        r["digest"],
        r["error"],
    )


def c_bytes(data):
    return "{" + ", ".join(f"0x{b:02x}" for b in data) + "}"


def main():
    print("/* Generated by gen_record_vectors.py. */")
    print("#pragma once")
    pcr = bytes(32)
    for name, r in RECORDS.items():
        raw = serialize(r)
        assert len(raw) == 76
        print(f"static const struct bl1_smc_record vec_{name} = {{")
        print(f"    .type = {{{', '.join(f'0x{b:02x}' for b in r['type'])}}},")
        print(f"    .load_addr = 0x{r['load_addr']:x}u, .entry_point = 0x{r['entry_point']:x}u,")
        print(f"    .length = {r['length']}u, .kind = {r['kind']}u,")
        print(f"    .digest = {c_bytes(r['digest'])},")
        print(f"    .error = 0x{r['error']:x}u,")
        print("};")
        print(f"static const uint8_t vec_{name}_bytes[76] = {c_bytes(raw)};")
        pcr = hashlib.sha256(pcr + hashlib.sha256(raw).digest()).digest()
        print(f"static const uint8_t vec_pcr_after_{name}[32] = {c_bytes(pcr)};")


if __name__ == "__main__":
    main()
