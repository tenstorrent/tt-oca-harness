"""Generate the SMC Boot ROM park address header for SEP BL1.

A forced park restarts SMC hart 0 at the `wfi; j` loop inside the ROM's secondary_main. The
loop has no symbol of its own, and secondary_main's entry would send hart 0 to main, so the
address is taken from the disassembly the SMC Boot ROM build writes (`objdump -d` output with
raw instruction bytes). The script fails unless it finds exactly that loop.
"""

import argparse
import re
import sys

# objdump separates an instruction line's columns with tabs:
# "<addr>:\t<raw bytes>\t<mnemonic>[\t<operands>]".
INSN = re.compile(r"^\s*([0-9a-f]+):\t(.*)$")
SYMBOL = re.compile(r"^[0-9a-f]+ <[^>]+>:\s*$")


def instructions(lines):
    for line in lines:
        m = INSN.match(line)
        if not m:
            continue
        fields = [f.strip() for f in m.group(2).split("\t")]
        if len(fields) < 2:
            continue
        yield int(m.group(1), 16), fields[1], fields[2] if len(fields) > 2 else ""


def find_park_loop(disassembly):
    lines = disassembly.splitlines()
    for i, line in enumerate(lines):
        if re.search(r"<secondary_main>:\s*$", line):
            body = []
            for nxt in lines[i + 1 :]:
                if SYMBOL.match(nxt):
                    break
                body.append(nxt)
            insns = list(instructions(body))
            for (addr, op, _), (_, op2, arg2) in zip(insns, insns[1:]):
                if op == "wfi" and op2 == "j" and arg2.split(" ")[0] == f"{addr:x}":
                    return addr
            raise SystemExit("secondary_main has no `wfi; j` park loop")
    raise SystemExit("no secondary_main in the SMC Boot ROM disassembly")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dis", required=True, help="SMC Boot ROM disassembly (.dis)")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    with open(args.dis, encoding="utf-8", errors="replace") as fh:
        addr = find_park_loop(fh.read())
    with open(args.out, "w", encoding="ascii") as fh:
        fh.write("/* Generated by park_addr.py from the SMC Boot ROM disassembly. */\n")
        fh.write("#pragma once\n")
        fh.write(f"#define SMU_BL1_SMC_ROM_PARK 0x{addr:08X}u\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
