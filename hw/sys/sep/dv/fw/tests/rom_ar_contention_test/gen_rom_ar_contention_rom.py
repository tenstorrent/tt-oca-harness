"""Generate the boot-ROM image and the firmware header of rom_ar_contention_test.

The image holds three ROM-resident hash routines and one data block:

* Routine k (k = 0, 1, 2) starts at ``k * ROUTINE_STRIDE`` and executes k ``nop``
  words before its loop, so the loop of each routine starts at a different
  offset inside a 64-bit fetch word and inside the IFU fetch stream.
* The loop body loads the eight 32-bit words of one group with ``lw`` from
  ROM and folds each into ``h = (h * 33) ^ w`` (``slli``/``add``/``xor``).
  Each ``lw`` sits between instructions that the IFU fetches from ROM, so
  the IFU fetch and the LSU load present AR at the boot-ROM mux in the same
  window. The loop ends on a taken backward branch, so the IFU fetches the
  loop head, which starts with a load, again.
* Calling convention: ``a0`` = data address, ``a1`` = number of 8-word
  groups (at least 1), ``a2`` = initial hash; returns the hash in ``a0``.
  Only caller-saved registers are used.
* The data block holds ``DATA_WORDS`` 32-bit words at ``DATA_OFF``. Word i is
  ``(0x9E3779B9 * (i + 1)) mod 2**32``: fixed, distinct, with both 16-bit
  halves non-zero, so a lane swap or a lost word changes the hash.

Outputs (both committed):

* ``hw/sys/sep/dv/cocotb/tests/rom_ar_contention_rom.hex``: ``$readmemh``
  image of the 64-bit boot-ROM words. Each line is one word; its low 32 bits
  are the lower address. ``@<word index>`` places the data block.
* ``rom_ar_contention_rom.h`` beside this script: the routine entry offsets,
  the data offset, the group size and the data words, for the firmware.

Usage::

    python3 gen_rom_ar_contention_rom.py          # write both files
    python3 gen_rom_ar_contention_rom.py --check  # exit 1 if a committed file differs
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_DV_ROOT = _HERE.parents[2]
sys.path.insert(0, str(_DV_ROOT / "cocotb" / "env"))

import sep_rv32_asm as rv  # noqa: E402

ROUTINES = 3
ROUTINE_STRIDE = 0x100
GROUP_WORDS = 8
DATA_OFF = 0x400
DATA_WORDS = 32
ROM_WORD_BYTES = 8

HEX_OUT = _DV_ROOT / "cocotb" / "tests" / "rom_ar_contention_rom.hex"
H_OUT = _HERE / "rom_ar_contention_rom.h"

_SPDX = (
    "SPDX-License-Identifier: Apache-2.0",
    "SPDX-FileCopyrightText: 2026 Tenstorrent USA, Inc.",
)


def data_words() -> list[int]:
    return [(0x9E3779B9 * (i + 1)) & 0xFFFF_FFFF for i in range(DATA_WORDS)]


def routine(k: int) -> list[int]:
    """Words of routine k, assembled at ROM offset ``k * ROUTINE_STRIDE``."""
    a = rv.Asm(k * ROUTINE_STRIDE)
    for _ in range(k):
        a.op(rv.addi(rv.ZERO, rv.ZERO, 0))
    a.label("loop")
    for i in range(GROUP_WORDS):
        a.op(
            rv.lw(rv.T0, rv.A0, 4 * i),
            rv.slli(rv.T1, rv.A2, 5),
            rv.add(rv.A2, rv.A2, rv.T1),
            rv.xor_(rv.A2, rv.A2, rv.T0),
        )
    a.op(rv.addi(rv.A0, rv.A0, 4 * GROUP_WORDS), rv.addi(rv.A1, rv.A1, -1))
    a.br("bne", rv.A1, rv.ZERO, "loop")
    a.op(rv.addi(rv.A0, rv.A2, 0), rv.jalr(rv.ZERO, rv.RA, 0))
    words = a.words()
    if 4 * len(words) > ROUTINE_STRIDE:
        raise ValueError(f"routine {k} is {4 * len(words)} bytes, over the stride")
    return words


def rom_image() -> dict[int, int]:
    """ROM byte offset -> 32-bit word for every word the image defines."""
    image: dict[int, int] = {}
    for k in range(ROUTINES):
        for i, w in enumerate(routine(k)):
            image[k * ROUTINE_STRIDE + 4 * i] = w
    if ROUTINES * ROUTINE_STRIDE > DATA_OFF:
        raise ValueError("routines overlap the data block")
    for i, w in enumerate(data_words()):
        image[DATA_OFF + 4 * i] = w
    return image


def hex_text() -> str:
    image = rom_image()
    lines = [f"// {s}" for s in _SPDX]
    lines.append("// Generated by fw/tests/rom_ar_contention_test/gen_rom_ar_contention_rom.py.")
    code_end = max(off for off in image if off < DATA_OFF) + 4
    sections = ((0, code_end), (DATA_OFF, DATA_OFF + 4 * DATA_WORDS))
    for start, end in sections:
        lines.append(f"@{start // ROM_WORD_BYTES:08x}")
        for off in range(start, end, ROM_WORD_BYTES):
            lo = image.get(off, rv.addi(rv.ZERO, rv.ZERO, 0))
            hi = image.get(off + 4, rv.addi(rv.ZERO, rv.ZERO, 0))
            lines.append(f"{hi:08x}{lo:08x}")
    return "\n".join(lines) + "\n"


def header_text() -> str:
    words = data_words()
    out = [f"// {s}" for s in _SPDX]
    out += [
        "//",
        "// Generated by gen_rom_ar_contention_rom.py from the same tables as",
        "// cocotb/tests/rom_ar_contention_rom.hex. Offsets are from the boot-ROM base.",
        "",
        "#ifndef ROM_AR_CONTENTION_ROM_H",
        "#define ROM_AR_CONTENTION_ROM_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define ROM_AR_ROUTINES {ROUTINES}u",
        f"#define ROM_AR_ROUTINE_STRIDE 0x{ROUTINE_STRIDE:x}u",
        f"#define ROM_AR_GROUP_WORDS {GROUP_WORDS}u",
        f"#define ROM_AR_DATA_OFF 0x{DATA_OFF:x}u",
        f"#define ROM_AR_DATA_WORDS {DATA_WORDS}u",
        "",
        "static const uint32_t rom_ar_data[ROM_AR_DATA_WORDS] = {",
    ]
    for i in range(0, DATA_WORDS, 7):
        out.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i : i + 7]) + ",")
    out += ["};", "", "#endif // ROM_AR_CONTENTION_ROM_H", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare, do not write")
    args = ap.parse_args()
    stale = []
    for path, text in ((HEX_OUT, hex_text()), (H_OUT, header_text())):
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.write_text(text)
    for path in stale:
        print(f"stale: {path}", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
