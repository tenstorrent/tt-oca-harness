#include "sep_outbound_filter.h"

// Mode constants (from OpenTitan run_p256.s)
#define MODE_VERIFY 0x1f8

// P256 scalar size
#define P256_SCALAR_WORDS 8

// OTBN status register values
#define OTBN_STATUS_IDLE 0x00
#define OTBN_STATUS_BUSY_EXECUTE 0x01

// OTBN command register values
#define OTBN_CMD_EXECUTE 0xD8
#define OTBN_CMD_SEC_WIPE_DMEM 0xC3
#define OTBN_CMD_SEC_WIPE_IMEM 0x1E

// ============================================================================
// Register and Memory Access - Using OCAH SEP Common Macros
// ============================================================================
// Uses the WRITE_REG/READ_REG macros from och_sep_common.h; sep.h / sep_addr.h
// provide absolute addresses, so no base offset is added.
// ============================================================================

// Memory access - word-indexed access to IMEM and DMEM
#define OTBN_IMEM(word) READ_MEM_WORD(SEP_TOP_OTBN_IMEM_BASE_ADDR, word)
#define OTBN_DMEM(word) READ_MEM_WORD(SEP_TOP_OTBN_DMEM_BASE_ADDR, word)
#define OTBN_IMEM_WRITE(word, value) WRITE_MEM_WORD(SEP_TOP_OTBN_IMEM_BASE_ADDR, word, value)
#define OTBN_DMEM_WRITE(word, value) WRITE_MEM_WORD(SEP_TOP_OTBN_DMEM_BASE_ADDR, word, value)

// OTBN DMEM offsets for P256 verification operation (extracted from ELF symbol table)
#define DMEM_MODE_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, mode) // mode (operation mode selection)
#define DMEM_OK_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, ok)     // ok (verification result)
#define DMEM_MSG_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, msg)   // msg (message digest to verify)
#define DMEM_R_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, r)       // r (signature R component input)
#define DMEM_S_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, s)       // s (signature S component input)
#define DMEM_X_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, x)       // x (public key x-coordinate)
#define DMEM_Y_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, y)       // y (public key y-coordinate)
#define DMEM_X_R_OFFSET OTBN_ADDR_T_INIT(p256_ecdsa, x_r)   // x_r (recovered x-coordinate output)

