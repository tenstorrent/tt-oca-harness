/**
 * Helper function to compare two uint32_t arrays and print results
 */
static int compare_arrays(const uint32_t *expected, const uint32_t *actual, size_t count,
                          const char *name) {
    int match = 1;
    for (size_t i = 0; i < count; i++) {
        if (expected[i] != actual[i]) {
            match = 0;
            break;
        }
    }

    printf("%s: %s\n", name, match ? "MATCH" : "MISMATCH");

    if (!match) {
        printf("  Expected: ");
        for (size_t i = 0; i < count; i++) {
            printf("%08x ", expected[i]);
        }
        printf("\n  Actual:   ");
        for (size_t i = 0; i < count; i++) {
            printf("%08x ", actual[i]);
        }
        printf("\n");
    }
    return match;
}

/**
 * Verify input data by reading back from DMEM and comparing with expected values
 */
static int verify_input_data(void) {
    printf("\n=== DMEM Input Data Verification ===\n");

    int errors = 0;
    uint32_t readback_data[P256_SCALAR_WORDS];

    // 1. Verify mode
    uint32_t readback_mode;
    if (otbn_read_dmem(DMEM_MODE_OFFSET, &readback_mode, 1) != 0) {
        printf("ERROR: Failed to read back mode - READ OPERATION FAILED\n");
        return -1;
    }
    uint32_t expected_mode = MODE_VERIFY;
    printf("Mode: %s (expected 0x%08x, actual 0x%08x)\n",
           (readback_mode == expected_mode) ? "MATCH" : "MISMATCH", expected_mode, readback_mode);
    if (readback_mode != expected_mode) {
        printf("  ERROR: Failed to read back Mode\n");
        errors++;
    }

    // 2. Verify message digest
    if (otbn_read_dmem(DMEM_MSG_OFFSET, readback_data, P256_SCALAR_WORDS) != 0) {
        printf("ERROR: Failed to read back message digest\n");
        return -1;
    }
    // Compare with original test vector
    if (!compare_arrays(test_message, readback_data, P256_SCALAR_WORDS, "Message Digest")) {
        errors++;
    }

    // 3. Verify signature R component
    if (otbn_read_dmem(DMEM_R_OFFSET, readback_data, P256_SCALAR_WORDS) != 0) {
        printf("ERROR: Failed to read back signature R\n");
        return -1;
    }
    // Compare with original test vector
    if (!compare_arrays(test_signature_r_otbn, readback_data, P256_SCALAR_WORDS, "Signature R")) {
        errors++;
    }

    // 4. Verify signature S component
    if (otbn_read_dmem(DMEM_S_OFFSET, readback_data, P256_SCALAR_WORDS) != 0) {
        printf("ERROR: Failed to read back signature S\n");
        return -1;
    }
    // Compare with original test vector
    if (!compare_arrays(test_signature_s_otbn, readback_data, P256_SCALAR_WORDS, "Signature S")) {
        errors++;
    }

    // 5. Verify public key X component
    if (otbn_read_dmem(DMEM_X_OFFSET, readback_data, P256_SCALAR_WORDS) != 0) {
        printf("ERROR: Failed to read back public key X\n");
        return -1;
    }
    // Compare with original test vector
    if (!compare_arrays(test_public_key_x_otbn, readback_data, P256_SCALAR_WORDS, "Public Key X")) {
        errors++;
    }

    // 6. Verify public key Y component
    if (otbn_read_dmem(DMEM_Y_OFFSET, readback_data, P256_SCALAR_WORDS) != 0) {
        printf("ERROR: Failed to read back public key Y\n");
        return -1;
    }
    // Compare with original test vector
    if (!compare_arrays(test_public_key_y_otbn, readback_data, P256_SCALAR_WORDS, "Public Key Y")) {
        errors++;
    }

    printf("=== Input Verification Summary ===\n");
    printf("Total errors: %d\n", errors);
    if (errors == 0) {
        printf("SUCCESS: All input data verified correctly!\n");
    } else {
        printf("FAILED: Input data verification found %d mismatches\n", errors);
    }
    printf("\n");

    return (errors == 0) ? 0 : -1;
}

/**
 * Execute OTBN P256 verification operation
 */
static int execute_verification(void) {
    printf("Executing OTBN P256 ECDSA verification...\n");

    // Debug: Check status before sending command
    uint32_t status_before = READ_REG(SEP_TOP_OTBN_STATUS_BASE_ADDR);
    printf("  [DEBUG] OTBN status before execute: 0x%02x\n", status_before);
    printf("  [DEBUG] Writing 0x%02x to OTBN_CMD_REG (addr=0x%08x)\n", OTBN_CMD_EXECUTE,
           SEP_TOP_OTBN_CMD_BASE_ADDR);

    // Send execute command
    WRITE_REG(SEP_TOP_OTBN_CMD_BASE_ADDR, OTBN_CMD_EXECUTE);

    // Debug: Check status after sending command
    uint32_t status_after = READ_REG(SEP_TOP_OTBN_STATUS_BASE_ADDR);
    printf("  [DEBUG] OTBN status after execute: 0x%02x\n", status_after);

    // Wait for completion
    if (otbn_wait_for_idle() != 0) {
        return -1;
    }

    // Check for errors
    uint32_t err_bits = READ_REG(SEP_TOP_OTBN_ERR_BITS_BASE_ADDR);
    if (err_bits != 0) {
        printf("ERROR: OTBN execution failed with error bits: 0x%08x\n", err_bits);
        return -1;
    }

    printf("OTBN verification completed successfully\n");
    return 0;
}

/**
 * Check verification results
 */
static int check_verification_results(void) {
    printf("Checking verification results...\n");

    // Debug: Print all the memory offsets we're using
    printf("Debug: Memory offsets:\n");
    printf("  DMEM_MODE_OFFSET = 0x%03x\n", DMEM_MODE_OFFSET);
    printf("  DMEM_OK_OFFSET   = 0x%03x\n", DMEM_OK_OFFSET);
    printf("  DMEM_X_R_OFFSET  = 0x%03x\n", DMEM_X_R_OFFSET);

    // Read the 'ok' status flag
    uint32_t ok_status;
    if (otbn_read_dmem(DMEM_OK_OFFSET, &ok_status, 1) != 0) {
        return -1;
    }

    // Debug: Also read mode to see what's there
    uint32_t mode_value;
    if (otbn_read_dmem(DMEM_MODE_OFFSET, &mode_value, 1) != 0) {
        return -1;
    }
    printf("Debug: Mode value at 0x%03x = 0x%08x\n", DMEM_MODE_OFFSET, mode_value);

    // Read the recovered x-coordinate
    uint32_t x_r_result[P256_SCALAR_WORDS];
    if (otbn_read_dmem(DMEM_X_R_OFFSET, x_r_result, P256_SCALAR_WORDS) != 0) {
        return -1;
    }

    printf("OK status: 0x%08x\n", ok_status);

    printf("Recovered x_r (raw OTBN format): ");
    for (int i = 0; i < P256_SCALAR_WORDS; i++) {
        printf("%08x ", x_r_result[i]);
    }
    printf("\n");

    // Use original R for comparison
    printf("Expected R (OTBN format): ");
    for (int i = 0; i < P256_SCALAR_WORDS; i++) {
        printf("%08x ", test_signature_r_otbn[i]);
    }
    printf("\n");

    // Check if ok_status indicates success (should be hardened boolean for valid signature)
    // Expected: 0x739 = HARDENED_BOOL_TRUE_XOR_COUNTER (0x639) XOR 256 (loop counter)
    const uint32_t EXPECTED_OK_VALUE = 0x739; // HARDENED_BOOL_TRUE_XOR_COUNTER XOR 256
    if (ok_status != EXPECTED_OK_VALUE) {
        printf("ERROR: OK status indicates verification FAILED\n");
        printf("       Expected: 0x%08x (HARDENED_BOOL_TRUE_XOR_COUNTER XOR 256)\n",
               EXPECTED_OK_VALUE);
        printf("       Actual:   0x%08x\n", ok_status);
        return -1;
    }
    printf("Verification basic input data checks PASSED (OK status = 0x%08x)\n", ok_status);

    // Check if recovered x_r matches the signature R component
    int r_match = 1;
    for (int i = 0; i < P256_SCALAR_WORDS; i++) {
        if (x_r_result[i] != test_signature_r_otbn[i]) {
            r_match = 0;
            break;
        }
    }

    if (!r_match) {
        printf("ERROR: Recovered x_r does not match signature R component\n");
        return -1;
    }

    printf("SUCCESS: Signature verification PASSED!\n");
    printf("  - OK status: VALID (0x%08x)\n", ok_status);
    printf("  - x_r matches R component\n");

    return 0;
}

/**
 * Main test function
 */
int main(void) {
    // Initialize outbound filter to allow testpass mailbox access
    sep_outbound_filter_init();

    printf("=== OTBN P256 ECDSA Signature Verification Test ===\n");
    printf("Using OpenTitan test vectors\n\n");

    int rc = 0;

    // Zero OTBN DMEM before load. A 32-bit beat on the 64-bit bus does not map
    // to a single 32-bit write through axi_lite_dw_converter, so init uses the
    // path that fills the array correctly.
    if (otbn_dmem_zero_init() != 0) {
        printf("FAILED: OTBN DMEM zero initialization failed\n");
        rc = -1;
        goto done;
    }

    // Load OTBN program
    if (otbn_load_program() != 0) {
        printf("FAILED: Could not load OTBN program\n");
        rc = -1;
        goto done;
    }

    // Setup test inputs
    if (setup_verification_inputs() != 0) {
        printf("FAILED: Could not setup verification inputs\n");
        rc = -1;
        goto done;
    }

    // Verify input data by reading back from DMEM
    if (verify_input_data() != 0) {
        printf("FAILED: Input data verification failed\n");
        rc = -1;
        goto done;
    }

    // Execute verification
    if (execute_verification() != 0) {
        printf("FAILED: OTBN execution failed\n");
        rc = -1;
        goto done;
    }

    // Check results
    if (check_verification_results() != 0) {
        printf("FAILED: Verification result check failed\n");
        rc = -1;
        goto done;
    }

    printf("\n=== Test PASSED ===\n");
    rc = 0;

done:
    if (rc == 0) {
        test_pass(0);
    } else {
        test_fail(1);
    }

    // Keep CPU alive after signaling completion.
    while (1) {
        __asm__("wfi");
    }
}
