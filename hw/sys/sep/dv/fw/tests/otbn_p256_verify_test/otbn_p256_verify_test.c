/*
 * OTBN P256 ECDSA Signature Verification Test
 *
 * This test demonstrates P256 ECDSA signature verification using the OTBN coprocessor.
 * It uses test vectors from OpenTitan's assembly test suite to verify correct operation.
 *
 * Test vectors are sourced from:
 * opentitan/sw/otbn/crypto/tests/p256_ecdsa_verify_test.s
 *
 * The test:
 * 1. Loads message digest, signature components (r, s), and public key into OTBN DMEM
 * 2. Executes the P256 ECDSA verification algorithm in OTBN
 * 3. Reads back the derived x_r value and confirms that it matches the signature R component
 *
 * Register addresses come from the generated `sep.h` / `sep_addr.h` headers.
 */

