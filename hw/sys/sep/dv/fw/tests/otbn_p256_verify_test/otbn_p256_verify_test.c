/**
 * Wait for OTBN to become idle
 */
static int otbn_wait_for_idle(void) {
    int timeout = 1000000; // Large timeout for simulation environments
    int print_counter = 0; // Debug: print every 100k iterations

    while (timeout-- > 0) {
        uint32_t status = READ_REG(SEP_TOP_OTBN_STATUS_BASE_ADDR);

        // Debug: Print status periodically
        if (++print_counter >= 100000) {
            printf("  [DEBUG] Waiting for OTBN idle... status=0x%02x (expect 0x%02x), timeout=%d\n",
                   status, OTBN_STATUS_IDLE, timeout);
            print_counter = 0;
        }

        if (status == OTBN_STATUS_IDLE) {
            return 0; // Success
        }
        // Add a small delay to prevent bus contention
        for (volatile int i = 0; i < 100; i++)
            ;
    }

    printf("ERROR: OTBN timeout waiting for idle state\n");
    return -1; // Timeout
}

/**
 * Manually initialize OTBN DMEM with zeros
 * This ensures a clean, predictable memory state
 */
static int otbn_dmem_zero_init(void) {
    printf("Manually initializing OTBN DMEM with zeros\n");

    // Wait for OTBN to be idle before starting
    if (otbn_wait_for_idle() != 0) {
        printf("ERROR: OTBN not idle before DMEM initialization\n");
        return -1;
    }

    // Zero out all visible DMEM locations
    // DMEM has 768 visible 32-bit words (3KB) over the bus interface
    const uint32_t dmem_size_words = 768;
    const uint32_t zero_value = 0x00000000;

    printf("  Writing zeros to DMEM addresses 0x000 to 0x%03x...\n", (dmem_size_words - 1) * 4);

    for (uint32_t addr = 0; addr < dmem_size_words; addr++) {
        OTBN_DMEM_WRITE(addr, zero_value);
    }

    // Reset the checksum register to 0 after DMEM initialization
    printf("  Resetting LOAD_CHECKSUM register to 0...\n");
    WRITE_REG(SEP_TOP_OTBN_LOAD_CHECKSUM_BASE_ADDR, 0x00000000);

    printf("OTBN DMEM zero initialization completed (%u words written)\n", dmem_size_words);
    return 0;
}

/**
 * Load OTBN instruction memory with P256 verification program
 */
static int otbn_load_program(void) {
    // Load IMEM (instruction memory)
    size_t imem_words = otbn_p256_ecdsa_imem_words;
    printf("Loading OTBN IMEM: %zu words\n", imem_words);

    for (size_t i = 0; i < imem_words; i++) {
        OTBN_IMEM_WRITE(i, otbn_p256_ecdsa_imem[i]);
    }

    // Load DMEM (data memory)
    size_t dmem_words = otbn_p256_ecdsa_dmem_words;
    printf("Loading OTBN DMEM: %zu words (includes P256 domain parameters)\n", dmem_words);

    for (size_t i = 0; i < dmem_words; i++) {
        OTBN_DMEM_WRITE(i, otbn_p256_ecdsa_dmem[i]);
    }

    // Verify the checksum if available
    if (OTBN_P256_ECDSA_EXPECTED_CRC != 0) {
        uint32_t actual_crc = READ_REG(SEP_TOP_OTBN_LOAD_CHECKSUM_BASE_ADDR);
        printf("Expected CRC: 0x%08x\n", OTBN_P256_ECDSA_EXPECTED_CRC);
        printf("Actual CRC:   0x%08x\n", actual_crc);

        if (actual_crc == OTBN_P256_ECDSA_EXPECTED_CRC) {
            printf("CRC validation PASSED\n");
        } else {
            printf("CRC validation FAILED\n");
            return -1;
        }
    }

    printf("OTBN program loaded successfully (IMEM + DMEM with domain parameters)\n");
    return 0;
}

/**
 * Write data to OTBN DMEM at specified offset
 */
static int otbn_write_dmem(uint32_t offset, const uint32_t *data, size_t word_count) {
    for (size_t i = 0; i < word_count; i++) {
        // Calculate word address in DMEM
        uint32_t word_addr = (offset + i * 4) / 4;
        OTBN_DMEM_WRITE(word_addr, data[i]);
    }
    return 0;
}

/**
 * Read data from OTBN DMEM at specified offset
 */
static int otbn_read_dmem(uint32_t offset, uint32_t *data, size_t word_count) {
    for (size_t i = 0; i < word_count; i++) {
        // Calculate word address in DMEM
        uint32_t word_addr = (offset + i * 4) / 4;
        data[i] = OTBN_DMEM(word_addr);
    }
    return 0;
}

