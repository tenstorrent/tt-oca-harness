/*
 * OTBN RSA-3072 Signature Verification Test
 *
 * Runs the OTBN RSA-3072 app to verify an RSA-3072 PKCS#1 v1.5 SHA-256
 * signature of the message "Hello OTBN." with public exponent 65537:
 * 1. Loads the RSA modulus, signature, and operation mode into OTBN DMEM
 * 2. Executes RSA modular exponentiation (signature^e mod n) in OTBN
 * 3. Compares the SHA-256 digest in the result with the expected digest;
 *    the PKCS#1 v1.5 padding bytes are not checked
 *
 * Adapted from OpenTitan RSA reference implementation.
 */

