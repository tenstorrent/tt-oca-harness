/**
 * Setup RSA verification inputs in OTBN DMEM
 */
static int setup_rsa_verification_inputs(void) {
    printf("Setting up RSA-3072 verification inputs...\n");

    // 1. Write RSA modulus (n) - 96 words
    printf("WRITING MODULUS\n");
    if (otbn_write_dmem(DMEM_N_OFFSET, test_modulus, RSA_3072_NUM_WORDS) != 0) {
        printf("FAILED TO WRITE MODULUS\n");
        return -1;
    }

    // 2. Write signature (96 words) to inout buffer
    printf("WRITING SIG\n");
    if (otbn_write_dmem(DMEM_INOUT_OFFSET, test_signature, RSA_3072_NUM_WORDS) != 0) {
        printf("FAILED TO WRITE SIG\n");
        return -1;
    }

    // 3. Write operation mode (RSA-3072 modexp with F4 exponent)
    static const uint32_t mode[1] = {MODE_RSA_3072_MODEXP_F4};
    printf("WRITING MODE\n");
    if (otbn_write_dmem(DMEM_MODE_OFFSET, mode, 1) != 0) {
        printf("FAILED TO WRITE MODE\n");
        return -1;
    }

    printf("Setup complete\n");
    return 0;
}

/**
 * Verify RSA input data by reading back from DMEM
 */
static int verify_rsa_input_data(void) {
    printf("\n=== DMEM Input Data Verification ===\n");

    int errors = 0;

    // 1. Verify RSA modulus
    uint32_t readback_modulus[RSA_3072_NUM_WORDS];
    if (otbn_read_dmem(DMEM_N_OFFSET, readback_modulus, RSA_3072_NUM_WORDS) != 0) {
        printf("ERROR: Failed to read back modulus\n");
        return -1;
    }
    if (!compare_arrays(test_modulus, readback_modulus, RSA_3072_NUM_WORDS, "RSA Modulus")) {
        errors++;
    }

    // 2. Verify signature
    uint32_t readback_signature[RSA_3072_NUM_WORDS];
    if (otbn_read_dmem(DMEM_INOUT_OFFSET, readback_signature, RSA_3072_NUM_WORDS) != 0) {
        printf("ERROR: Failed to read back signature\n");
        return -1;
    }
    if (!compare_arrays(test_signature, readback_signature, RSA_3072_NUM_WORDS, "Signature")) {
        errors++;
    }

    // 3. Verify mode
    uint32_t readback_mode;
    if (otbn_read_dmem(DMEM_MODE_OFFSET, &readback_mode, 1) != 0) {
        printf("ERROR: Failed to read back mode\n");
        return -1;
    }
    uint32_t expected_mode = MODE_RSA_3072_MODEXP_F4;
    printf("Mode: %s (expected 0x%08x, actual 0x%08x)\n",
           (readback_mode == expected_mode) ? "MATCH" : "MISMATCH", expected_mode, readback_mode);
    if (readback_mode != expected_mode) {
        errors++;
    }

    printf("=== Input Verification Summary ===\n");
    printf("Total errors: %d\n", errors);
    if (errors == 0) {
        printf("SUCCESS: All input data verified correctly!\n");
    } else {
        printf("FAILED: Input data verification found %d mismatches\n", errors);
    }
    printf("\n");

    return (errors == 0) ? 0 : -1;
}

/**
 * Execute OTBN RSA verification operation
 */
static int execute_verification(void) {
    printf("Executing OTBN RSA-3072 verification...\n");

    // Debug: Check status before sending command
    uint32_t status_before = READ_REG(SEP_TOP_OTBN_STATUS_BASE_ADDR);
    printf("  [DEBUG] OTBN status before execute: 0x%02x\n", status_before);
    printf("  [DEBUG] Writing 0x%02x to OTBN_CMD_REG (addr=0x%08x)\n", OTBN_CMD_EXECUTE,
           SEP_TOP_OTBN_CMD_BASE_ADDR);

    // Send execute command
    WRITE_REG(SEP_TOP_OTBN_CMD_BASE_ADDR, OTBN_CMD_EXECUTE);

    // Debug: Check status after sending command
    uint32_t status_after = READ_REG(SEP_TOP_OTBN_STATUS_BASE_ADDR);
    printf("  [DEBUG] OTBN status after execute: 0x%02x\n", status_after);

    // Wait for completion
    if (otbn_wait_for_idle() != 0) {
        return -1;
    }

    // Check for errors
    uint32_t err_bits = READ_REG(SEP_TOP_OTBN_ERR_BITS_BASE_ADDR);
    if (err_bits != 0) {
        printf("ERROR: OTBN execution failed with error bits: 0x%08x\n", err_bits);
        return -1;
    }

    printf("OTBN verification completed successfully\n");
    return 0;
}

/**
 * Check RSA verification results
 */
static int check_rsa_verification_results(void) {
    printf("Checking RSA verification results...\n");

    // Read result from DMEM inout buffer (OTBN writes decrypted/verified data here)
    uint32_t result[RSA_3072_NUM_WORDS];
    if (otbn_read_dmem(DMEM_INOUT_OFFSET, result, RSA_3072_NUM_WORDS) != 0) {
        printf("ERROR: Failed to read result from DMEM\n");
        return -1;
    }

    printf("Result from OTBN (all words):\n");
    for (int i = 0; i < RSA_3072_NUM_WORDS; i++) {
        printf("  [%2d] 0x%08x\n", i, result[i]);
    }

    // The result is the PKCS#1 v1.5 encoded message, 0x00 || 0x01 || PS || 0x00 ||
    // DigestInfo || Hash. The hash is its last 32 bytes, which are the first 8
    // words of the least-significant-word-first result.
    uint32_t extracted_digest[SHA256_DIGEST_WORDS];
    for (int i = 0; i < SHA256_DIGEST_WORDS; i++) {
        extracted_digest[i] = result[i];
    }

    printf("\nExtracted digest (first 8 words):\n");
    for (int i = 0; i < SHA256_DIGEST_WORDS; i++) {
        printf("  [%d] 0x%08x\n", i, extracted_digest[i]);
    }

    printf("\nExpected digest:\n");
    for (int i = 0; i < SHA256_DIGEST_WORDS; i++) {
        printf("  [%d] 0x%08x\n", i, test_message_digest[i]);
    }

    // Compare extracted digest with expected message digest
    if (compare_arrays(test_message_digest, extracted_digest, SHA256_DIGEST_WORDS,
                       "Message Digest")) {
        printf("\nSUCCESS: RSA-3072 signature verification PASSED!\n");
        printf("  Message: \"Hello OTBN.\"\n");
        printf("  Hash: SHA-256\n");
        printf("  Signature: RSA-3072 with PKCS#1 v1.5 padding\n");
        printf("  Verification: VALID\n");
        return 0;
    } else {
        printf("\nERROR: Signature verification FAILED - digest mismatch\n");
        return -1;
    }
}

