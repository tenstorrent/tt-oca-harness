// RSA-3072 key and digest sizes
#define RSA_3072_NUM_BITS 3072
#define RSA_3072_NUM_BYTES (RSA_3072_NUM_BITS / 8)  // 384 bytes
#define RSA_3072_NUM_WORDS (RSA_3072_NUM_BYTES / 4) // 96 words

// SHA-256 digest size
#define SHA256_DIGEST_BITS 256
#define SHA256_DIGEST_BYTES (SHA256_DIGEST_BITS / 8)  // 32 bytes
#define SHA256_DIGEST_WORDS (SHA256_DIGEST_BYTES / 4) // 8 words

// RSA mode constant from OTBN run_rsa.s
// MODE_RSA_3072_MODEXP_F4: RSA-3072 modular exponentiation with F4 exponent (e=65537)
#define MODE_RSA_3072_MODEXP_F4 0x1be

// OTBN status register values
#define OTBN_STATUS_IDLE 0x00

// OTBN command register values
#define OTBN_CMD_EXECUTE 0xD8

// ============================================================================
// Register and Memory Access Macros
// ============================================================================

// Memory access - word-indexed access to IMEM and DMEM
#define OTBN_DMEM(word) READ_MEM_WORD(SEP_TOP_OTBN_DMEM_BASE_ADDR, word)
#define OTBN_IMEM_WRITE(word, value) WRITE_MEM_WORD(SEP_TOP_OTBN_IMEM_BASE_ADDR, word, value)
#define OTBN_DMEM_WRITE(word, value) WRITE_MEM_WORD(SEP_TOP_OTBN_DMEM_BASE_ADDR, word, value)

// ============================================================================
// OTBN DMEM Symbol Offsets (extracted from ELF symbol table)
// ============================================================================

#define DMEM_MODE_OFFSET OTBN_ADDR_T_INIT(rsa_3072_app, mode) // Operation mode
#define DMEM_N_OFFSET OTBN_ADDR_T_INIT(rsa_3072_app, rsa_n)   // RSA modulus (n)
#define DMEM_INOUT_OFFSET \
    OTBN_ADDR_T_INIT(rsa_3072_app, inout) // Input: signature, Output: decrypted message

