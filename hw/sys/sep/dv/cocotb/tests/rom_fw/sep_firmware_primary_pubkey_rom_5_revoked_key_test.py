"""Primary manifest selects REVOKED ROM key slot 5 -> the backup boots.

The stimulus and assertions are in ``sep_pubkey_rom_revoked_primary_base``; this module picks the
slot and the outcome. ``sep_efuse_lc_prod_pubk_revoke5.toml`` is ``sep_efuse_lc_prod.toml`` plus
only ``CHIPLET_PUBK_REVOKE`` bit 5. Only the primary selects slot 5; the backup keeps the shipped
ROM slot 0 (``configs/oca_secure_boot_test.yaml``), which bit 5 does not revoke, so the backup
boots. The run is not terminal.

The primary slot is grafted from ``oca_rom_key5_boot.bin``: its modulus hashes to the slot-5
digest in the ``bootrom/prod`` compiled-in table (``include/key_digests.h``, generated by
``tools/generate_key_digests.py``) and its signature verifies under that key. The ROM authorizes
before it consults the revocation bitmap, so ``PUBK_UNAUTHORIZED`` and ``PUBK_SLOT_UNPROVISIONED``
are forbidden: either one means the graft did not land. One ``RSA_EXEC`` in total, after the
backup read: the primary is refused before a modexp. Needs ``+esrc_noise_force``: the backup's
RSA-3072 modexp stalls OTBN until EDN grants entropy.
"""

