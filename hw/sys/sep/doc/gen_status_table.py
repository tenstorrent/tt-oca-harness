"""Generate the SEP_MSG_* status-code table for rom.adoc from the ROM header.

The header is the single source of truth for status codes: the boot ROM compiles
against it, and the SEP VP's decoder is configured to read this same file
(STATUS_VALUES_PATH), so names in VP logs come from it too. Generating the
document table from it as well keeps a third copy from drifting -- the previous
flow generated all three from a TSV that did not come across with the rest of
the tree.

Usage:  python3 gen_status_table.py [-o gen/status_values.adoc]
"""

import argparse
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
HEADER = HERE.parent / "bootrom" / "prod" / "include" / "status_values.h"

DEFINE = re.compile(r"^#define\s+(SEP_MSG_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\s*$")


def parse(path):
    """Yield (name, value) in file order.

    Deliberately two columns, not three. The header carries only one grouping
    comment, so a "group" column derived from the nearest preceding comment
    labels every later code with a heading it does not belong to -- worse than
    no grouping at all.
    """
    for line in path.read_text().splitlines():
        m = DEFINE.match(line)
        if m:
            yield m.group(1), int(m.group(2), 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-o", "--output", default=str(HERE / "gen" / "status_values.adoc"))
    args = ap.parse_args()

    rows = list(parse(HEADER))
    if not rows:
        raise SystemExit(f"no SEP_MSG_* defines found in {HEADER}")

    dupes = {}
    for name, value in rows:
        dupes.setdefault(value, []).append(name)
    collisions = {v: n for v, n in dupes.items() if len(n) > 1}

    out = [
        # The generated file is committed, so it carries the SPDX block the
        # repository's license gate requires of every tracked file.
        "// SPDX-License-Identifier: Apache-2.0",
        "// SPDX-FileCopyrightText: 2026 Tenstorrent USA, Inc.",
        "// GENERATED by hw/sys/sep/doc/gen_status_table.py -- DO NOT EDIT.",
        "// Source: hw/sys/sep/bootrom/prod/include/status_values.h",
        "",
        # rom.adoc cross-references this table as <<tbl:sep_msg_codes>>.
        "[[tbl:sep_msg_codes]]",
        f".SEP_MSG_* status codes ({len(rows)} defined)",
        '[width="100%",cols="25%,75%",options="header"]',
        "[grid=rows]",
        "[frame=ends]",
        "|===",
        "|*Value* |*Name*",
    ]
    for name, value in rows:
        out.append(f"|`0x{value:04X}` |`{name}`")
    out += ["|===", ""]

    if collisions:
        out.append("NOTE: The following code values are shared by more than one name, so a")
        out.append(
            "decoded status is ambiguous between them: "
            + "; ".join(
                f"`0x{v:04X}` -- " + ", ".join(f"`{n}`" for n in names)
                for v, names in sorted(collisions.items())
            )
            + "."
        )
        out.append("")

    pathlib.Path(args.output).write_text("\n".join(out))
    print(
        f"wrote {args.output}: {len(rows)} codes"
        + (f", {len(collisions)} colliding value(s)" if collisions else "")
    )


if __name__ == "__main__":
    main()
