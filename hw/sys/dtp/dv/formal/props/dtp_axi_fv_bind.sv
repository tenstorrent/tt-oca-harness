// Attaches the shared AXI checker to the manager port of each JTAG2AXI bridge of every jtag_ptap
// instance under the dtp formal top: the bridge is the master, whose rules each instance asserts,
// and the port's target is the slave, whose rules it assumes. A bridge keeps one transfer open at
// a time. The AXI4-Lite ports have no ID, length, size, burst, lock or LAST signals, so those
// inputs take the single-beat constants of a 32-bit port.

bind jtag_ptap ocah_axi_fv #(
  .IS_LITE             (1'b1),
  .ADDR_WIDTH          ($bits(axil_smc_otp_jtag_req_o.aw.addr)),
  .DATA_WIDTH          ($bits(axil_smc_otp_jtag_req_o.w.data)),
  .ID_WIDTH            (1),
  .MAX_OUTSTANDING     (1),
  .ASSUME_MASTER_RULES (1'b0),
  .ASSUME_SLAVE_RULES  (1'b1)
) u_ocah_axi_fv_smc_otp (
  .aclk    (clk_i),
  .aresetn (rst_n_i),
  .awid    ('0),
  .awaddr  (axil_smc_otp_jtag_req_o.aw.addr),
  .awlen   ('0),
  .awsize  (3'd2),
  .awburst (2'b01),
  .awlock  (1'b0),
  .awprot  (axil_smc_otp_jtag_req_o.aw.prot),
  .awvalid (axil_smc_otp_jtag_req_o.aw_valid),
  .awready (axil_smc_otp_jtag_resp_i.aw_ready),
  .wdata   (axil_smc_otp_jtag_req_o.w.data),
  .wstrb   (axil_smc_otp_jtag_req_o.w.strb),
  .wlast   (1'b1),
  .wvalid  (axil_smc_otp_jtag_req_o.w_valid),
  .wready  (axil_smc_otp_jtag_resp_i.w_ready),
  .bid     ('0),
  .bresp   (axil_smc_otp_jtag_resp_i.b.resp),
  .bvalid  (axil_smc_otp_jtag_resp_i.b_valid),
  .bready  (axil_smc_otp_jtag_req_o.b_ready),
  .arid    ('0),
  .araddr  (axil_smc_otp_jtag_req_o.ar.addr),
  .arlen   ('0),
  .arsize  (3'd2),
  .arburst (2'b01),
  .arlock  (1'b0),
  .arprot  (axil_smc_otp_jtag_req_o.ar.prot),
  .arvalid (axil_smc_otp_jtag_req_o.ar_valid),
  .arready (axil_smc_otp_jtag_resp_i.ar_ready),
  .rid     ('0),
  .rdata   (axil_smc_otp_jtag_resp_i.r.data),
  .rresp   (axil_smc_otp_jtag_resp_i.r.resp),
  .rlast   (1'b1),
  .rvalid  (axil_smc_otp_jtag_resp_i.r_valid),
  .rready  (axil_smc_otp_jtag_req_o.r_ready)
);

