// Attaches dtp_j2a_props to each JTAG2AXI bridge of every jtag_ptap instance under the dtp formal
// top, one instance per bridge: the SMC OTP and SEP OTP AXI4-Lite bridges and the SMC fabric AXI4
// bridge. The demultiplexer, the error slave and tdr2axi sit in the generate block of the bridge's
// port variant, so each bind names its own bridge's block. The AXI4-Lite port has none of the
// AXI4-only attributes, so those inputs take 0. Internal signals reach the property module through
// these port lists only; the RTL carries no properties.

