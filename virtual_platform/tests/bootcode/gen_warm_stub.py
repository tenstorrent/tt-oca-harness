"""Regenerate the checked-in warm-stub word modules from their .S sources."""

import argparse
import pathlib
import shutil
import subprocess
import tempfile
from dataclasses import dataclass

HERE = pathlib.Path(__file__).resolve().parent
TOOLS = (
    "riscv64-unknown-elf-gcc",
    "riscv64-unknown-elf-objcopy",
    "riscv64-unknown-elf-objdump",
)
ABI = ("-march=rv32im_zicsr", "-mabi=ilp32")


@dataclass(frozen=True)
class ProgramSpec:
    source: pathlib.Path
    output: pathlib.Path
    load_address: int
    entry: str
    constant_prefix: str


SPECS = (
    ProgramSpec(
        source=HERE / "warm_handler_stub.S",
        output=HERE / "warm_handler_words.py",
        load_address=0xC0030000,
        entry="_warm_stub",
        constant_prefix="WARM_HANDLER",
    ),
    ProgramSpec(
        source=HERE / "warm_fault_stub.S",
        output=HERE / "warm_fault_words.py",
        load_address=0xC0030000,
        entry="_warm_fault_stub",
        constant_prefix="WARM_FAULT",
    ),
)


def assemble(spec: ProgramSpec) -> tuple[list[int], str]:
    """Assemble the stub and return little-endian words plus disassembly."""
    for tool in TOOLS:
        if not shutil.which(tool):
            raise RuntimeError(f"{tool} is required to regenerate the warm stub")

    with tempfile.TemporaryDirectory() as temp_dir:
        work = pathlib.Path(temp_dir)
        obj = work / "warm_handler.o"
        elf = work / "warm_handler.elf"
        binary = work / "warm_handler.bin"
        subprocess.run(
            [TOOLS[0], *ABI, "-nostdlib", "-c", spec.source, "-o", obj],
            check=True,
        )
        subprocess.run(
            [
                TOOLS[0],
                *ABI,
                "-nostdlib",
                "-Wl,--build-id=none",
                f"-Wl,-Ttext={spec.load_address:#x}",
                f"-Wl,-e,{spec.entry}",
                obj,
                "-o",
                elf,
            ],
            check=True,
        )
        subprocess.run(
            [TOOLS[1], "-O", "binary", "-j", ".text", elf, binary],
            check=True,
        )
        raw = binary.read_bytes()
        disassembly = subprocess.run(
            [TOOLS[2], "-d", elf],
            check=True,
            capture_output=True,
            text=True,
        ).stdout

    if len(raw) % 4:
        raise RuntimeError(
            f"{spec.source.name} assembles to {len(raw)} bytes, not a multiple of four"
        )
    words = [int.from_bytes(raw[offset : offset + 4], "little") for offset in range(0, len(raw), 4)]
    return words, disassembly


def render(spec: ProgramSpec, words: list[int]) -> str:
    """Render the generated Python module imported by the pytest."""
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# SPDX-FileCopyrightText: 2026 Tenstorrent USA, Inc.",
        "",
        f"# Generated by gen_warm_stub.py from {spec.source.name}; do not edit.",
        f"{spec.constant_prefix}_LOAD_ADDRESS = 0x{spec.load_address:08X}",
        f"{spec.constant_prefix}_WORDS = (",
        *(f"    0x{word:08X}," for word in words),
        ")",
        "",
    ]
    return "\n".join(lines)


def verify() -> bool:
    return all(
        spec.output.is_file() and spec.output.read_text() == render(spec, assemble(spec)[0])
        for spec in SPECS
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--show-disasm", action="store_true")
    args = parser.parse_args()

    stale = False
    for spec in SPECS:
        words, disassembly = assemble(spec)
        if args.show_disasm:
            print(f"== {spec.source.name} ==\n{disassembly}")
        generated = render(spec, words)
        if args.verify:
            if not spec.output.is_file() or spec.output.read_text() != generated:
                print(f"{spec.output.name} is stale; run {pathlib.Path(__file__).name}")
                stale = True
            else:
                print(f"{spec.output.name}: {len(words)} words match {spec.source.name}")
            continue

        spec.output.write_text(generated)
        print(f"wrote {spec.output.name}: {len(words)} words from {spec.source.name}")
    return int(stale)


if __name__ == "__main__":
    raise SystemExit(main())
