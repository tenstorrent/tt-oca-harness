"""Generate a flattened C header from a SystemRDL register space.

The C sibling of `rdlsvh.py`: the same flattened view (address/offset defines
with arrays unrolled per index, per-register defaults, per-field mask/shift
defines, and per-register bitfield structs), emitted as C.

This is not what `peakrdl c-header` produces. That exporter names things
`BLOCK__REG__FIELD_bm`, while firmware here is written against the flat
`BLOCK_REG_FIELD_MASK` / `BLOCK_REG_REG_ADDR` family that the SV and Python
headers also use. Keeping the three emitters name-compatible is the point:
a constant means the same thing whichever language reads it.
"""

import argparse
import os
import sys
from pathlib import Path

from systemrdl import RDLCompiler, RDLCompileError, RDLWalker
from systemrdl.node import AddressableNode, MemNode

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common.regcollect import FieldCollector, build_struct_fields, compute_default  # noqa: E402

SCRIPT_VERSION = "r2025-06-03"
BAR = "//=============================================================================="


def storage_type(width: int) -> str:
    """Smallest stdint type that holds a register of this width."""
    for bits in (8, 16, 32, 64):
        if width <= bits:
            return f"uint{bits}_t"
    return None


class CHeaderListener(FieldCollector):
    def __init__(self, root, args):
        super().__init__(root, args.addrmap, args.shorten_names)
        self.addr_width = int(args.addr_width)
        self.input_file = args.input_rdl_file
        self.add_total_struct = args.add_total_struct
        self.guard = None

        self.header_text = ""
        self.addr_text = ""
        self.default_text = ""
        self.struct_text = ""
        self.bitfield_text = ""
        self.footer_text = ""

    def define_addr(self, name, value):
        digits = -(self.addr_width // -4)
        return f"#define {name} (0x{value:0{digits}X})\n"

    def section(self, title):
        return f"\n{BAR}\n// {title}\n{BAR}\n\n"

    def enter_Addrmap(self, node):
        super().enter_Addrmap(node)
        name = node.get_path_segment()
        if self.shorten_names or node.parent == self.root:
            def_name = node.get_path_segment(array_suffix="_{index:d}_").upper() \
                if self.shorten_names else name.upper()
        else:
            def_name = self.def_name(node)

        if node.parent == self.root:
            self.guard = f"{self.target_addr_map.upper()}_REG_H"
            self.header_text += f"""\
/*******************************************************************************
 * Header file for register addresses and fields
 *
 * This file was auto-generated by this script:
 *       {os.path.basename(sys.argv[0])}   ({SCRIPT_VERSION})
 * ... from this input file:
 *       {os.path.basename(self.input_file)}
 * ... using this as the target address space:
 *       {self.target_addr_map}
 *
 * This file should not be modified by hand.
 *
 ******************************************************************************/

#ifndef {self.guard}
#define {self.guard}
"""
            self.default_text += self.section(
                f"Reset Values for Address Map: {self.target_addr_map}"
            )
            self.bitfield_text += self.section(
                f"Bit Fields for Address Map: {self.target_addr_map}"
            )
            # Bootcode's vector.S includes this header through the assembler's
            # preprocessor, so the typedefs have to be hidden from it. Everything
            # above is plain integer defines and stays visible to assembly.
            self.struct_text += (
                "\n#ifndef __ASSEMBLER__\n\n#include <stdint.h>\n"
                + self.section(f"Structs for Address Map: {self.target_addr_map}")
            )
            self.footer_text += "\n#endif // __ASSEMBLER__\n\n#endif\n"

        if not self.under_target:
            return

        if node.parent == self.root:
            # Top-level addrmap base is 0 in the spec; use the lowest child address.
            base = min(
                (c.absolute_address for c in node.children(unroll=True)
                 if isinstance(c, AddressableNode)),
                default=0,
            )
            size = node.size - base
        else:
            base = node.absolute_address
            size = node.size

        self.addr_text += self.section(f"Addresses for Address Map: {name}")
        self.addr_text += self.define_addr(def_name + "_REG_MAP_BASE_ADDR", base)
        self.addr_text += self.define_addr(def_name + "_REG_MAP_SIZE", size)

    def enter_Regfile(self, node):
        if self.under_target:
            self.addr_text += self.section(f"Register File: {node.get_path_segment()}")
            self.addr_text += self.define_addr(
                self.def_name(node) + "_REG_FILE_BASE_ADDR", node.absolute_address)
            self.addr_text += self.define_addr(
                self.def_name(node) + "_REG_FILE_SIZE", node.size)

    def enter_Mem(self, node):
        if self.under_target:
            self.addr_text += self.section(f"Memory: {node.get_path_segment()}")
            self.addr_text += self.define_addr(
                self.def_name(node) + "_MEM_BASE_ADDR", node.absolute_address)
            self.addr_text += self.define_addr(
                self.def_name(node) + "_MEM_SIZE", node.size)

    def enter_Reg(self, node):
        super().enter_Reg(node)
        if not self.under_target:
            return
        if self.shorten_names:
            fullname = (
                node.parent.get_path_segment(array_suffix="_{index:d}_").upper()
                + "_"
                + node.get_path_segment(array_suffix="_{index:d}_")
            )
        else:
            fullname = self.path_minus_root(node).upper()

        # No address constants for registers inside a memory array.
        if not (node.is_array and isinstance(node.parent, MemNode)):
            self.addr_text += self.define_addr(fullname + "_REG_OFFSET", node.address_offset)
            self.addr_text += self.define_addr(fullname + "_REG_ADDR", node.absolute_address)

    def process_fields(self):
        for reg_name, reg in self.regs.items():
            reg_width = reg.regwidth
            ctype = storage_type(reg_width)

            for f in reg.fields:
                max_mask = 2**reg_width - 1
                mask = (max_mask << f.low) & ~(max_mask << (f.high + 1))
                self.bitfield_text += (
                    f"#define {reg_name}_{f.name.upper()}_MASK 0x{mask:X}\n"
                    f"#define {reg_name}_{f.name.upper()}_SHIFT {f.low}\n\n"
                )

            digits = -(reg_width // -4)
            self.default_text += (
                f"#define {reg_name}_REG_DEFAULT "
                f"(0x{compute_default(reg.fields):0{digits}X})\n"
            )

            # A register wider than the largest stdint gets no struct; its
            # addresses, masks and default above are still emitted.
            if ctype is None:
                continue

            self.struct_text += "typedef struct {\n"
            for name, width in build_struct_fields(reg.fields):
                self.struct_text += f"    {ctype} {name} : {width};\n"
            self.struct_text += f"}} {reg_name}_reg_t;\n\n"

            self.struct_text += (
                "typedef union {\n"
                f"    {ctype} val;\n"
                f"    {reg_name}_reg_t f;\n"
                f"}} {reg_name}_reg_u;\n\n"
            )

        if self.add_total_struct:
            rows = []
            for inst, reginst in self.reg_inst_count.items():
                dims = "".join(f"[{d}]" for d in reginst.dims) if reginst.dims else ""
                rows.append(f"    {reginst.type_name}_reg_u {inst.lower()}{dims};\n")
            self.struct_text += "typedef struct {\n"
            self.struct_text += "".join(rows)
            self.struct_text += f"}} {self.target_addr_map}_regmap_t;\n\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_rdl_file")
    parser.add_argument("output_h_file")
    parser.add_argument("-u", "--udp_rdl_file", required=True,
                        help="the PeakRDL UDP RDL file (./regblock_udps.rdl)")
    parser.add_argument("-t", "--top", help="address map to use as the top")
    parser.add_argument("-a", "--addrmap",
                        help="address map (instance name) for which to generate output")
    parser.add_argument("-i", "--incdir", action="append",
                        help="directory to search for included files")
    parser.add_argument("-s", "--shorten_names", action="store_true",
                        help="use shorter constant names")
    parser.add_argument("--addr_width", default=32, help="width of address bus")
    parser.add_argument("--add_total_struct", action="store_true",
                        help="append a struct naming every register instance and its "
                        "union type, the only place the header records which type an "
                        "instance has (constants elsewhere are named per type)")
    args = parser.parse_args()

    rdlc = RDLCompiler()
    try:
        rdlc.compile_file(args.udp_rdl_file)
        rdlc.compile_file(args.input_rdl_file, incl_search_paths=args.incdir)
        root = rdlc.elaborate(args.top)
    except RDLCompileError:
        sys.exit(1)

    listener = CHeaderListener(root, args)
    RDLWalker(unroll=True).walk(root, listener)
    listener.process_fields()

    with open(args.output_h_file, "w") as f:
        f.write(listener.header_text)
        f.write(listener.addr_text)
        f.write(listener.default_text)
        f.write(listener.bitfield_text)
        f.write(listener.struct_text)
        f.write(listener.footer_text)


if __name__ == "__main__":
    main()
