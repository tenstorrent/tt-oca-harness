"""Generate a flattened SystemVerilog header from a SystemRDL register space.

Emits, for every register instance under the target address map: address and
offset localparams (arrays unrolled per index), per-register default-value
localparams, per-field mask/shift localparams, and per-register packed struct
typedefs.
"""

import argparse
import os
import sys
from pathlib import Path

from systemrdl import RDLCompileError, RDLCompiler, RDLWalker
from systemrdl.node import AddressableNode, MemNode

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common.rdlview import parse_rdl_params  # noqa: E402
from common.regcollect import FieldCollector, build_struct_fields, compute_default  # noqa: E402

SCRIPT_VERSION = "r2025-06-03"
BAR = "//=============================================================================="


class SvhListener(FieldCollector):
    def __init__(self, root, args):
        super().__init__(root, args.addrmap, args.shorten_names)
        self.add_total_struct = args.add_total_struct
        self.addr_width = int(args.addr_width)
        self.input_file = args.input_rdl_file

        self.header_text = ""
        self.addr_text = ""
        self.struct_text = ""
        self.bitfield_text = ""
        self.default_text = ""
        self.footer_text = ""

    def localparam(self, name, value):
        decl = f"localparam {'long' if self.addr_width > 32 else ''}int unsigned {name}"
        digits = -(self.addr_width // -4)
        return f"{decl:110}    = {self.addr_width}'h{value:0{digits}X};\n"

    def section(self, title):
        return f"\n\n{BAR}\n// {title}\n{BAR}\n\n"

    def enter_Addrmap(self, node):
        super().enter_Addrmap(node)
        name = node.get_path_segment()
        if self.shorten_names or node.parent == self.root:
            def_name = (
                node.get_path_segment(array_suffix="_{index:d}_").upper()
                if self.shorten_names
                else name.upper()
            )
        else:
            def_name = self.def_name(node)

        if node.parent == self.root:
            header_def = self.target_addr_map.upper()
            self.header_text += f"""\
// SPDX-License-Identifier: Apache-2.0
// SPDX-FileCopyrightText: 2026 Tenstorrent USA, Inc.

/*******************************************************************************
 * Header file for register addresses and fields
 *
 * This file was auto-generated by this script:
 *       {os.path.basename(sys.argv[0])}   ({SCRIPT_VERSION})
 * ... from this input file:
 *       {os.path.basename(self.input_file)}
 * ... using this as the target address space:
 *       {self.target_addr_map}
 *
 * This file should not be modified by hand.
 *
 ******************************************************************************/

`ifndef {header_def}_REG_SVH
`define {header_def}_REG_SVH

"""
            self.bitfield_text += (
                f"\n\n\n{BAR}\n// Bit Fields for Address Map: {self.target_addr_map}\n{BAR}\n\n"
            )
            self.footer_text += "\n`endif\n"

        if not self.under_target:
            return

        if node.parent == self.root:
            # Top-level addrmap base is 0 in the spec; use the lowest child address.
            base = min(
                (
                    c.absolute_address
                    for c in node.children(unroll=True)
                    if isinstance(c, AddressableNode)
                ),
                default=0,
            )
            size = node.size - base
        else:
            base = node.absolute_address
            size = node.size

        self.addr_text += self.section(f"Addresses for Address Map: {name}") + "\n"
        self.addr_text += self.localparam(def_name + "_REG_MAP_BASE_ADDR", base)
        self.addr_text += self.localparam(def_name + "_REG_MAP_SIZE", size) + "\n\n"
        self.struct_text += "\n\n\n"

    def enter_Regfile(self, node):
        if self.under_target:
            self.addr_text += self.section(f"Register File: {node.get_path_segment()}")
            self.addr_text += self.localparam(
                self.def_name(node) + "_REG_FILE_BASE_ADDR", node.absolute_address
            )
            self.addr_text += (
                self.localparam(self.def_name(node) + "_REG_FILE_SIZE", node.size) + "\n"
            )

    def enter_Mem(self, node):
        if self.under_target:
            self.addr_text += self.section(f"Memory: {node.get_path_segment()}")
            self.addr_text += self.localparam(
                self.def_name(node) + "_MEM_BASE_ADDR", node.absolute_address
            )
            self.addr_text += self.localparam(self.def_name(node) + "_MEM_SIZE", node.size) + "\n"

    def enter_Reg(self, node):
        super().enter_Reg(node)
        if not self.under_target:
            return
        if self.shorten_names:
            fullname = (
                node.parent.get_path_segment(array_suffix="_{index:d}_").upper()
                + "_"
                + node.get_path_segment(array_suffix="_{index:d}_")
            )
        else:
            fullname = self.path_minus_root(node).upper()

        # No address constants for registers inside a memory array.
        if not (node.is_array and isinstance(node.parent, MemNode)):
            self.addr_text += self.localparam(fullname + "_REG_OFFSET", node.address_offset)
            self.addr_text += self.localparam(fullname + "_REG_ADDR", node.absolute_address)

    def process_fields(self):
        self.struct_text += "\n"

        for reg_name, reg in self.regs.items():
            reg_width = reg.regwidth
            fields = reg.fields
            mask_type = {
                8: "byte unsigned",
                16: "shortint unsigned",
                32: "int unsigned",
                64: "longint unsigned",
            }.get(reg_width, f"bit [{reg_width - 1}:0]")
            type_width = max(len(mask_type), len("int unsigned"))

            for f in fields:
                max_mask = 2**reg_width - 1
                mask = (max_mask << f.low) & ~(max_mask << (f.high + 1))
                mask_decl = f"localparam {mask_type:>{type_width}} {reg_name}_{f.name.upper()}_MASK"
                shift_decl = (
                    f"localparam {'int unsigned':>{type_width}} {reg_name}_{f.name.upper()}_SHIFT"
                )
                self.bitfield_text += f"{mask_decl:110}    = {reg_width}'h{mask:X};\n"
                self.bitfield_text += f"{shift_decl:110}    = {f.low};\n\n"

            struct_fields = [
                f"    logic [{width - 1}:0]   {name} ;\n"
                for name, width in build_struct_fields(fields)
            ]

            self.struct_text += "typedef struct packed {\n"
            self.struct_text += "".join(reversed(struct_fields))
            self.struct_text += f"}} {reg_name.lower()}_reg_t;\n\n\n\n"

        if self.add_total_struct:
            rows = []
            for inst, reginst in self.reg_inst_count.items():
                if reginst.dims:
                    vec = "".join(f"[{d - 1}:0]" for d in reginst.dims)
                    rows.append(f"    {reginst.type_name.lower()}_reg_t {vec} {inst.lower()};\n")
                else:
                    rows.append(f"    {reginst.type_name.lower()}_reg_t {inst.lower()};\n")
            self.struct_text += "typedef struct packed {\n"
            self.struct_text += "".join(reversed(rows))
            self.struct_text += f"}} {self.target_addr_map}_regmap_t;\n"

    def process_defaults(self):
        self.default_text += self.section("Default values for registers")

        for reg_name, reg in self.regs.items():
            if reg.regwidth > 64:
                continue
            reg_reset = compute_default(reg.fields)
            decl = f"localparam longint unsigned {reg_name}_REG_DEFAULT"
            width_str = "32" if reg.regwidth <= 32 else "64"
            digits = -(reg.regwidth // -4)
            self.default_text += f"{decl:110}    = {width_str}'h{reg_reset:0{digits}X};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_rdl_file")
    parser.add_argument("output_svh_file")
    parser.add_argument(
        "-u", "--udp_rdl_file", required=True, help="the PeakRDL UDP RDL file (./regblock_udps.rdl)"
    )
    parser.add_argument("-t", "--top", help="address map to use as the top")
    parser.add_argument(
        "-a", "--addrmap", help="address map (instance name) for which to generate output"
    )
    parser.add_argument(
        "-i", "--incdir", action="append", help="directory to search for included files"
    )
    parser.add_argument(
        "-s", "--shorten_names", action="store_true", help="use shorter constant names"
    )
    parser.add_argument("--addr_width", default=32, help="width of address bus")
    parser.add_argument(
        "--add_total_struct", action="store_true", help="generate total struct for all registers"
    )
    parser.add_argument(
        "--structs_file",
        default=None,
        help="if given, write per-register typedef struct definitions AND "
        "per-field mask/shift localparams to this file instead of including "
        "them in the main output file",
    )
    parser.add_argument(
        "-P",
        dest="rdl_params",
        action="append",
        default=[],
        metavar="NAME=VALUE",
        help="override an addrmap parameter (repeatable)",
    )
    args = parser.parse_args()

    rdlc = RDLCompiler()
    try:
        rdlc.compile_file(args.udp_rdl_file)
        rdlc.compile_file(args.input_rdl_file, incl_search_paths=args.incdir)
        root = rdlc.elaborate(args.top, parameters=parse_rdl_params(args.rdl_params) or None)
    except RDLCompileError:
        sys.exit(1)

    listener = SvhListener(root, args)
    RDLWalker(unroll=True).walk(root, listener)
    listener.process_fields()
    listener.process_defaults()

    with open(args.output_svh_file, "w") as f:
        f.write(listener.header_text)
        f.write(listener.addr_text)
        f.write(listener.default_text)
        if args.structs_file is None:
            f.write(listener.bitfield_text)
            f.write(listener.struct_text)
        f.write(listener.footer_text)

    if args.structs_file is not None:
        structs_def = os.path.splitext(os.path.basename(args.structs_file))[0].upper()
        with open(args.structs_file, "w") as sf:
            sf.write(f"""\
/*******************************************************************************
 * Per-field mask/shift localparams and per-register typedef struct definitions
 *
 * This file was auto-generated by this script:
 *       {os.path.basename(sys.argv[0])}   ({SCRIPT_VERSION})
 * ... from this input file:
 *       {os.path.basename(args.input_rdl_file)}
 *
 * This file should not be modified by hand.
 *
 ******************************************************************************/

`ifndef {structs_def}_SVH
`define {structs_def}_SVH
""")
            sf.write(listener.bitfield_text)
            sf.write(listener.struct_text)
            sf.write("\n`endif\n")


if __name__ == "__main__":
    main()
